class S {
  const S(this.lang);
  final String lang; // zh | en

  String call(String key) =>
      (lang == 'en' ? _en[key] : _zh[key]) ?? _zh[key] ?? key;

  String state(String s) => call('state.$s');
  String path(String p) => call('path.$p');
  String errorCode(String c) {
    final v = lang == 'en' ? _en['err.$c'] : _zh['err.$c'];
    return v ?? call('err.generic');
  }

  static const supported = ['zh', 'en'];
  static String languageName(String l) => l == 'en' ? 'English' : '中文';
}

